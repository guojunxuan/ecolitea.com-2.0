import { chromium } from '@playwright/test'
const browser = await chromium.launch()
const page = await browser.newPage({ viewport: { width: 390, height: 844 } })
await page.goto('http://localhost:3001/blogs/small-details-better-everyday-products', { waitUntil: 'networkidle' })
await page.locator('h2[id]').nth(2).evaluate((h) => h.scrollIntoView({ block: 'start' }))
await page.waitForTimeout(300)
const trigger = page.getByRole('button', { name: 'Table of contents' })
const label = await trigger.locator('span').first().evaluate((el) => { const s = getComputedStyle(el); return { transform: s.textTransform, size: s.fontSize, spacing: s.letterSpacing } })
await page.screenshot({ path: 'output/blog-detail-concepts/verify/closed.png' })
await trigger.click()
const menu = page.locator('nav[aria-label="Table of contents"]:visible')
const bar = await trigger.locator('..').boundingBox()
const box = await menu.boundingBox()
await page.screenshot({ path: 'output/blog-detail-concepts/verify/open.png' })
await page.keyboard.press('Escape')
const afterEsc = await menu.count()
await trigger.click()
await menu.getByRole('link').first().click()
await page.waitForTimeout(300)
console.log(JSON.stringify({ label, bar, menu: box, dialogs: await page.getByRole('dialog').count(), afterEsc, afterLink: await menu.count(), url: page.url() }))
await browser.close()
